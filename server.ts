// Admin API: Toggle approval status
app.post("/api/astrology-hub/toggle-approval", (req, res) => {
  try {
    const { type, id } = req.body;
    if (!type || !id) {
      return res.status(400).json({ success: false, error: "Type and id parameters are required." });
    }

    let itemFound = false;

    if (type === "daily") {
      const idx = db.dailyInsights.findIndex(i => i.id === id);
      if (idx >= 0) {
        db.dailyInsights[idx].isApproved = !db.dailyInsights[idx].isApproved;
        itemFound = true;
      }
    } else if (type === "weekly") {
      const idx = db.weeklyForecasts.findIndex(i => i.id === id);
      if (idx >= 0) {
        db.weeklyForecasts[idx].isApproved = !db.weeklyForecasts[idx].isApproved;
        itemFound = true;
      }
    } else if (type === "blog") {
      const idx = db.blogArticles.findIndex(i => i.id === id);
      if (idx >= 0) {
        db.blogArticles[idx].isApproved = !db.blogArticles[idx].isApproved;
        itemFound = true;
      }
    }

    if (!itemFound) {
      return res.status(404).json({ success: false, error: "Item not found in current record." });
    }

    saveDb(db);
    res.json({ success: true, message: "Approval state toggled successfully.", db });
  } catch (err: any) {
    res.status(500).json({ success: false, error: err.message });
  }
});

