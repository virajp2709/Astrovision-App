// Main query and automated generation endpoint
app.get("/api/astrology-hub", async (req, res) => {
  try {
    const todayStr = new Date().toISOString().split("T")[0];
    const currentMondayStr = getMondayStr();

    let dbUpdatesNeeded = false;

    // 1. Check if Daily Insight exists for today (active auto-generation)
    const hasTodayInsight = db.dailyInsights.some(di => di.date === todayStr);
    if (!hasTodayInsight) {
      console.log(`[Automated Hub] Daily Insight missing for today (${todayStr}). Instantiating new automated entry...`);
      try {
        const generated = await autoGenerateDaily(todayStr);
        db.dailyInsights.unshift(generated);
        dbUpdatesNeeded = true;
      } catch (err) {
        console.error("Failed to auto-generate daily content on page access:", err);
      }
    }

    // 2. Check if Weekly Forecast exists for current Monday (active weekly automation)
    const hasWeeklyForecast = db.weeklyForecasts.some(wf => wf.weekStarting === currentMondayStr);
    if (!hasWeeklyForecast) {
      console.log(`[Automated Hub] Weekly Forecast missing for current week (${currentMondayStr}). Instantiating...`);
      try {
        const generated = await autoGenerateWeekly(currentMondayStr);
        db.weeklyForecasts.unshift(generated);
        dbUpdatesNeeded = true;
      } catch (err) {
        console.error("Failed to auto-generate weekly content on page access:", err);
      }
    }

    // Save changes back to disk
    if (dbUpdatesNeeded) {
      saveDb(db);
    }

    // Return current compiled database
    res.json({
      success: true,
      dailyInsights: db.dailyInsights,
      weeklyForecasts: db.weeklyForecasts,
      blogArticles: db.blogArticles
    });
  } catch (error: any) {
    res.status(500).json({ success: false, error: error.message });
  }
});

