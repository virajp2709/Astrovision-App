// API endpoint to create standard Razorpay Order
app.post("/api/create-order", async (req, res) => {
  try {
    const { amount_inr, booking_id } = req.body;

    if (!amount_inr || isNaN(amount_inr) || amount_inr <= 0) {
      return res.status(400).json({ error: "A valid amount in INR is required to establish the transaction." });
    }

    // Convert INR to Paise (e.g. 100 INR = 10000 Paise)
    const amountInPaise = Math.round(amount_inr * 100);

    if (amountInPaise < 100) {
      return res.status(400).json({ error: "The minimum checkout amount is 100 paise (1 INR)." });
    }

    const options = {
      amount: amountInPaise,
      currency: "INR",
      receipt: `rec_${booking_id || Math.floor(100000 + Math.random() * 900000)}`,
    };

    let order = null;
    let successfulKeyId = "";
    let lastError: any = null;

    // Filter and try each set of credentials until one works or we exhaust the list
    for (const cred of RAZORPAY_CREDENTIALS_CHAIN) {
      const trimmedKey = cred.keyId.trim();
      const trimmedSecret = cred.keySecret.trim();

      if (!trimmedKey || !trimmedSecret) {
        continue;
      }

      try {
        console.log(`[create-order] Checking auth alignment with ${cred.label} - key ID: "${trimmedKey.substring(0, 15)}..."`);
        const rzp = new Razorpay({
          key_id: trimmedKey,
          key_secret: trimmedSecret
        });

        // Test if we can successfully create the order with these credentials
        order = await rzp.orders.create(options);
        successfulKeyId = trimmedKey;
        console.log(`[create-order] Success! Authenticated via ${cred.label}. Order ID: ${order.id}`);
        break; // Succesfully created order, exit sequence
      } catch (err: any) {
        console.warn(`[create-order] Credentials failed for ${cred.label}. Details:`, err.message || err);
        lastError = err;
      }
    }

    if (!order) {
      console.error("[create-order] Exhausted all fallback credentials chains. Fail state reached.");
      throw lastError || new Error("All loaded and hardcoded Razorpay credential authentication chains failed.");
    }

    return res.status(200).json({
      order_id: order.id,
      amount: order.amount,
      currency: order.currency,
      key_id: successfulKeyId // Return successfully mated key to client for checkout matching
    });
  } catch (error: any) {
    console.error("Razorpay Error (create-order) - Raw:", error);
    try {
      console.error("Razorpay Error (create-order) - Stringified:", JSON.stringify(error, null, 2));
    } catch (e) {
      console.error("Could not stringify Razorpay error:", e);
    }

    const detailedMessage = error.error?.description || error.description || error.message || "Failed to create payment order with Razorpay.";
    const detailedCode = error.error?.code || error.code || "UNKNOWN_ERROR";

    return res.status(500).json({ 
      error: detailedMessage,
      code: detailedCode,
      raw: error
    });
  }
});

// API endpoint to verify transaction authenticity via signature matching
app.post("/api/verify-payment", async (req, res) => {
  try {
    const { razorpay_order_id, razorpay_payment_id, razorpay_signature } = req.body;

    if (!razorpay_order_id || !razorpay_payment_id || !razorpay_signature) {
      return res.status(400).json({ error: "Missing required Razorpay signature parameters." });
    }

    // Try verifying signature with all known secrets in chain
    let verified = false;

    const secretsToTry = RAZORPAY_CREDENTIALS_CHAIN
      .map(c => c.keySecret.trim())
      .filter(Boolean);

    for (const secret of secretsToTry) {
      try {
        const hmac = crypto.createHmac("sha256", secret);
        hmac.update(`${razorpay_order_id}|${razorpay_payment_id}`);
        const generatedSignature = hmac.digest("hex");
        if (generatedSignature === razorpay_signature) {
          verified = true;
          console.log(`[verify-payment] Verification PASSED matching secret slice: "${secret.substring(0, 4)}..."`);
          break;
        }
      } catch (cryptoErr) {
        console.warn("[verify-payment] Error generating hash block: ", cryptoErr);
      }
    }

    if (verified) {
      return res.status(200).json({
        success: true,
        message: "Celestial transaction verified by secure SHA-256 signature alignment successfully."
      });
    } else {
      return res.status(400).json({
        success: false,
        error: "Signature mismatch. Authenticity verification failed."
      });
    }
  } catch (error: any) {
    console.error("Razorpay Error (verify-payment) - Raw:", error);
    try {
      console.error("Razorpay Error (verify-payment) - Stringified:", JSON.stringify(error, null, 2));
    } catch (e) {
      console.error("Could not stringify Razorpay verification error:", e);
    }
    return res.status(500).json({ 
      error: error.message || "Error processing payment signature verification.",
      raw: error
    });
  }
});

// Start Express server and integrate with Vite build-cycle
async function startServer() {
  // Vite dev server mounting or static production bundle rendering
  if (process.env.NODE_ENV !== "production") {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: "spa",
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), "dist");
    app.use(express.static(distPath));
    app.get("*", (req, res) => {
      res.sendFile(path.join(distPath, "index.html"));
    });
  }

  app.listen(PORT, "0.0.0.0", () => {
    console.log(`Server listening at http://localhost:${PORT}`);
  });
}

startServer();
